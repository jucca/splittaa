#!/usr/bin/env node
/**
 * Generates docs/generated/db-schema.md from convex/schema.ts.
 * Usage: node scripts/generate-schema-doc.mjs [--check]
 */
import { readFileSync, writeFileSync, existsSync, mkdirSync } from "fs";
import { join, dirname } from "path";

const root = process.cwd();
const schemaPath = join(root, "convex/schema.ts");
const outPath = join(root, "docs/generated/db-schema.md");

const schema = readFileSync(schemaPath, "utf8");

const tableStarts = [...schema.matchAll(/^\s+(\w+):\s*defineTable\(/gm)];

const tables = tableStarts.map((match, i) => {
  const name = match[1];
  const start = match.index;
  const end =
    i + 1 < tableStarts.length
      ? tableStarts[i + 1].index
      : schema.indexOf("});", start);
  const block = schema.slice(start, end);

  const indexes = [...block.matchAll(/\.index\("([^"]+)",\s*\[([^\]]+)\]\)/g)].map(
    (m) => ({ name: m[1], fields: m[2].replace(/\s/g, "") })
  );
  const searchIndexes = [
    ...block.matchAll(/\.searchIndex\("([^"]+)",\s*\{\s*searchField:\s*"([^"]+)"/g),
  ].map((m) => ({ name: m[1], field: m[2] }));

  return { name, indexes, searchIndexes };
});

const generated = `<!-- AUTO-GENERATED by scripts/generate-schema-doc.mjs — do not edit -->

# Database schema

Generated from \`convex/schema.ts\`. Re-run \`npm run generate:schema-doc\` after schema changes.

| Table | Indexes | Search indexes |
|-------|---------|----------------|
${tables
  .map((t) => {
    const idx =
      t.indexes.map((i) => `\`${i.name}\` (${i.fields})`).join("<br>") || "—";
    const search =
      t.searchIndexes.map((s) => `\`${s.name}\` → \`${s.field}\``).join("<br>") ||
      "—";
    return `| \`${t.name}\` | ${idx} | ${search} |`;
  })
  .join("\n")}

## Query patterns (personal / dashboard)

| Use case | Pattern |
|----------|---------|
| Expenses I paid (1-to-1) | \`by_user_and_group\`: \`paidByUserId\` + \`groupId: undefined\` |
| Expenses others paid where I'm in splits | \`by_group\`: \`groupId: undefined\` + filter splits |
| Settlements I paid (1-to-1) | \`by_user_and_group\` on settlements |
| Settlements I received (1-to-1) | \`by_receiver_and_group\` |
| Group expenses / settlements | \`by_group\` on \`groupId\` |

Helpers: \`convex/_lib/personal.ts\` (\`getPersonalExpensesForUser\`, \`getPersonalSettlementsForUser\`).
Auth: \`convex/_lib/authorize.ts\` (\`assertGroupMember\`, \`assertGroupMembers\`).
`;

const checkMode = process.argv.includes("--check");

if (checkMode) {
  if (!existsSync(outPath)) {
    console.error("check-schema-doc: docs/generated/db-schema.md is missing");
    console.error("Run: npm run generate:schema-doc");
    process.exit(1);
  }
  const existing = readFileSync(outPath, "utf8");
  if (existing !== generated) {
    console.error(
      "check-schema-doc: docs/generated/db-schema.md is out of date"
    );
    console.error("Run: npm run generate:schema-doc");
    process.exit(1);
  }
  console.log("check-schema-doc: OK");
} else {
  mkdirSync(dirname(outPath), { recursive: true });
  writeFileSync(outPath, generated);
  console.log(`Wrote ${outPath}`);
}
